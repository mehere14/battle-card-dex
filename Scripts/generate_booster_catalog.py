#!/usr/bin/env python3
"""Generate the app's compact, image-free booster catalogue from artwork QA output."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / ".generated/booster-pack-art/manifest.json").read_text())
fallback_years = {**{f"pop{i}": 2003 + i for i in range(1, 10)}, "swsh7": 2021}
rows = []
for set_id, value in manifest["sets"].items():
    if value.get("status") != "processed" or not value.get("variants"):
        continue
    match = re.search(r"(19|20)\d{2}", value.get("forum_date") or "")
    year = int(match.group()) if match else fallback_years.get(set_id)
    if not year:
        raise SystemExit(f"Missing release year for {set_id}")
    name = (value.get("cached_names") or [value.get("forum_name") or set_id])[0]
    rows.append((year, name, set_id, value["variants"][0]["path"]))
rows.sort(key=lambda row: (-row[0], row[1].casefold(), row[2]))

def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)

lines = [
    "// Generated by Scripts/generate_booster_catalog.py. Do not edit by hand.",
    "import Foundation",
    "",
    "extension BoosterPackArtwork {",
    "    static let allPacks: [BoosterPackArtwork] = [",
]
for year, name, set_id, path in rows:
    lines.append(f"        .init(setID: {quoted(set_id)}, name: {quoted(name)}, year: {year}, recordID: {quoted('catalog-pack-art-' + set_id.lower())}, sourceVariantPath: {quoted(path)}),")
lines += ["    ]", "}", ""]
(ROOT / "BattleCardDex/Features/GeneratedBoosterPackCatalog.swift").write_text("\n".join(lines))
print(f"generated {len(rows)} representative packs")
